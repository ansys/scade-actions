from pathlib import Path


def test_release_workflow_skips_missing_rolling_tags():
    workflow = Path(".github/workflows/release.yml").read_text(encoding="utf-8")

    assert 'for tag in "${X}" "${X}.${Y}"; do' in workflow
    assert (
        'git ls-remote --exit-code --tags origin "refs/tags/${tag}"'
        in workflow
    )
    assert 'git push --delete origin "${tag}"' in workflow
